// Flat config. The PoC shipped no linter at all; this is the floor for a
// package other people install.
//
// Type-aware rules are on deliberately. The mechanism this SDK is built around
// stamps attributes onto spans it did not create, so most of what can go wrong
// is a wrong-shaped value reaching an `unknown`, which only a type-aware rule
// sees.
import { defineConfig, globalIgnores } from 'eslint/config';
import js from '@eslint/js';
import globals from 'globals';
import tseslint from 'typescript-eslint';
import prettier from 'eslint-config-prettier';

export default defineConfig([
  globalIgnores([
    'dist/**',
    'coverage/**',
    'junit.xml',
    // Generated by contract/generate.ts. Lint it and you are reviewing the
    // emitter's output instead of the emitter.
    'src/attributes.gen.ts',
  ]),

  js.configs.recommended,
  tseslint.configs.strictTypeChecked,
  tseslint.configs.stylisticTypeChecked,

  {
    languageOptions: {
      globals: globals.node,
      parserOptions: {
        // This config file is not in any tsconfig, and the type-aware rules
        // refuse to parse a file no project claims.
        projectService: {
          allowDefaultProject: ['eslint.config.js'],
        },
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      // The source uses `.ts` import specifiers, rewritten at build time by
      // `rewriteRelativeImportExtensions`. That is what lets `node --test` run
      // the tests directly.
      '@typescript-eslint/consistent-type-imports': [
        'error',
        { prefer: 'type-imports', fixStyle: 'inline-type-imports' },
      ],
    },
  },

  {
    files: ['test/**/*.ts'],
    rules: {
      // `node:test`'s `test()` returns a promise the runner itself awaits.
      // Every top-level test would otherwise need a `void`, which reads as
      // noise and teaches people to add `void` where it actually matters.
      '@typescript-eslint/no-floating-promises': 'off',
    },
  },

  prettier,
]);
